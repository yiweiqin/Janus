function mean(values) {
  return values.length ? values.reduce((sum, value) => sum + value, 0) / values.length : 0;
}

function pearson(left, right) {
  const n = left.length;
  if (!n) return 0;
  const ml = mean(left);
  const mr = mean(right);
  let cov = 0;
  let vl = 0;
  let vr = 0;
  for (let at = 0; at < n; at += 1) {
    const dl = left[at] - ml;
    const dr = right[at] - mr;
    cov += dl * dr;
    vl += dl * dl;
    vr += dr * dr;
  }
  const denominator = Math.sqrt(vl * vr);
  return denominator === 0 ? 0 : cov / denominator;
}

