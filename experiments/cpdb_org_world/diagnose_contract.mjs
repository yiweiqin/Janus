function spearman(left, right) {
  const rank = (values) => {
    const order = values.map((value, at) => ({ value, at })).sort((a, b) => a.value - b.value);
    const out = new Array(values.length);
    let at = 0;
    while (at < order.length) {
      let end = at;
      while (end + 1 < order.length && order[end + 1].value === order[at].value) end += 1;
      const average = (at + end) / 2 + 1;
      for (let cursor = at; cursor <= end; cursor += 1) out[order[cursor].at] = average;
      at = end + 1;
    }
    return out;
  };
  return pearson(rank(left), rank(right));
}

