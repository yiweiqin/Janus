import fs from 'node:fs/promises';
import path from 'node:path';
import crypto from 'node:crypto';
import { writeRun, verifyRun } from './artifacts.mjs';
import { aggregateDirectory } from './statistics.mjs';

const out = process.argv[2] || 'experiments/tdb_probe_benchmark/runs/review-v3-multiseed';
const families = Number(process.argv[3] || 70);
const repeats = Number(process.argv[4] || 2);
const seeds = [20260907, 20260908, 20260909, 20260910, 20260911];
const root = path.resolve(out);
await fs.mkdir(root, { recursive: true });
const results = [];
for (const seed of seeds) {
  const dir = path.join(root, `seed-${seed}`);
  const run = await writeRun({ out: dir, seed, families, repeats });
  const verification = await verifyRun(dir);
  const statistics = await aggregateDirectory(dir);
  await fs.writeFile(path.join(dir, 'statistics.json'), JSON.stringify(statistics, null, 2) + String.fromCharCode(10), { flag: 'w' });
  results.push({ seed, directory: dir, verification, statistics, metrics: run.metrics });
}
function mean(xs) { return xs.reduce((a, b) => a + b, 0) / xs.length; }
function sd(xs) { const m = mean(xs); return Math.sqrt(mean(xs.map(x => (x - m) ** 2))); }
const policies = ['noop', 'heuristic', 'learned', 'probeSearch', 'oracle'];
const aggregate = Object.fromEntries(policies.map(policy => {
  const values = results.map(r => r.metrics.byPolicy[policy].meanGain);
  const success = results.map(r => r.metrics.byPolicy[policy].successRate);
  return [policy, { seedCount: values.length, meanGain: mean(values), sdGain: sd(values), meanSuccessRate: mean(success), sdSuccessRate: sd(success), values }];
}));
const hashFile = async file => crypto.createHash('sha256').update(await fs.readFile(file)).digest('hex');
const childHashes = {};
for (const r of results) { childHashes[r.seed] = {}; for (const file of ['metrics.json','manifest.json','episodes.jsonl','report.md','statistics.json']) childHashes[r.seed][file] = await hashFile(path.join(r.directory, file)); }
const summary = { evidenceLevel: 'SYNTHETIC_EXECUTION_ONLY', realWorldValidated: false, seeds, families, repeats,
  testFamiliesPerSeed: results[0].metrics.counts.independentTestFamilies, aggregate,
  perSeed: results.map(r => ({ seed: r.seed, counts: r.metrics.counts, interaction: r.metrics.interaction, byPolicy: r.metrics.byPolicy, statistics: r.statistics })),
  limitations: ['all families are generated by one invoice generator', 'seed spread is not real task-family diversity', 'no real independent evaluator', 'cross-seed SD is not a confidence interval'],
  artifactVerification: results.every(r => r.verification.verified), childHashes };
await fs.writeFile(path.join(root, 'aggregate.json'), JSON.stringify(summary, null, 2) + String.fromCharCode(10));
await fs.writeFile(path.join(root, 'manifest.json'), JSON.stringify({ version: 'tdb-multiseed-v1', seeds, families, repeats, childRuns: results.map(r => r.directory), aggregateShaScope: 'aggregate.json plus child artifacts', childHashes }, null, 2) + String.fromCharCode(10));
console.log(JSON.stringify({ root, artifactVerification: summary.artifactVerification, testFamiliesPerSeed: summary.testFamiliesPerSeed, aggregate }, null, 2));
